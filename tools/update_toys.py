#!/usr/bin/env python3
"""Writes ToyList.lua: the game's toys, spells, items, mounts and pets, in the order Clicky numbers them.

An entry's Clicky number is its place in the list, so the list only ever grows at the end: the
first run writes the toys sorted by item ID, then the spells sorted by spell ID, then the items
sorted by item ID, then the mounts and the pets; later runs append the toys, then the spells, the
items, the mounts and the pets not listed yet (each sorted by ID among themselves). An entry that
left the game keeps its place.

A toy is written as its item ID, a spell as "s" and its spell ID, an item as "i" and its item ID,
a mount as "m" and its mount ID, a pet as "p", its species ID, ":" and the display ID of one of its
species' looks (a species can come in several colors, and each is an entry), or 0: the species'
looks the list doesn't have, or all its looks when the player has none of those (a pet can have a
look no table gives its species, seen in play).
After the list come the toys whose Flags in the Toy table have the 2 bit (TOY_HIDDEN), the mounts
whose Flags in the Mount table have the 0x40 bit (MOUNT_HIDDEN) and the pet species whose Flags have
HideFromJournal or HideUntilLearned (PET_HIDDEN), which Clicky's grid lists only when the player has
them; and the pet species whose looks are random (PET_RANDOM_LOOK).
They come from the game's tables for the live build (wago.tools): the Toy table's ItemID; the
spells a character can learn: the SkillLineAbility table's Spell (the spells the game's skill lines
teach), the SpecializationSpells table's SpellID and OverridesSpellID (a specialization's own
spells, such as Penance), the TraitDefinition table's SpellID, OverridesSpellID and VisibleSpellID
(talents, such as Mind Blast, and the spell a talent replaces or shows as) and the PvpTalent table's
SpellID; the ItemXItemEffect
table's ItemID for an ItemEffect with TriggerType 0 (the items with a "Use:" effect; an item whose
effects are only "Equip:" ones, such as a guild tabard, has nothing to use), less the toys, in the
game or listed. A use whose spell's text (the Spell table's Description_lang) is "$?s<id>[...][]" is
shown only to a character who knows spell <id> and doesn't count: gems are eaten so, by the Earthen
only (Ingest Minerals, 436341). The Mount table's ID. The BattlePetSpecies table's ID with each
display ID of its CreatureID: its row in the Creature table (DisplayID_0 to DisplayID_3; 0 is none)
and its rows in the CreatureXDisplayInfo table (CreatureDisplayInfoID), which has looks past those
four, and the BattlePetDisplayOverride table's CreatureDisplayInfoID for its BattlePetSpeciesID (a
look a player condition gives, as Uuna's questline does); and 0 for each species, which is the only
look of a species whose Flags have RandomDisplay (0x800): its pets change look each summon. Python
standard library only. Running it again for the same build changes nothing.
"""

import csv
import io
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST_PATH = os.path.join(ROOT, "ToyList.lua")
USER_AGENT = "clicky-toylist/1.0 (+https://github.com/shadowpaxa/clicky)"
BUILDS_URL = "https://wago.tools/api/builds/latest"
# Without ?build= wago serves a build that isn't the live one.
CSV_URL = "https://wago.tools/db2/%s/csv?build=%s"
# Entries are (kind, ID): kind "" is a toy, in the order they are appended. A pet's ID is
# (species ID, display ID).
KINDS = ("", "s", "i", "m", "p")

HEADER = """\
-- The game's toys (an item ID), spells ("s" and a spell ID), items ("i" and an item ID), mounts
-- ("m" and a mount ID) and pets ("p", a species ID, ":" and the display ID of one of its looks). An
-- entry's number in Clicky's macros is its 0-based place in this list, so the list only ever grows
-- at the end: nothing is reordered or removed, and an entry that left the game keeps its place.
-- Generated by tools/update_toys.py from the game's tables; don't edit by hand.
-- Last updated from WoW build %(build)s.

local _, ns = ...

ns.TOY_LIST_BUILD = "%(build)s"
ns.TOY_IDS = {
"""

# The tables after the list, written whole each run, ID -> true or a number: what Clicky's grid lists
# only when the player has it, the pet species whose looks aren't listed, and what its filters read
# where the game has no API for it (a source is Enum.BattlePetSources, a mount type's flags
# Enum.MountTypeFlag; a toy's expansion and a mount's source come from the game, C_Item.GetItemInfo
# and C_MountJournal.GetMountInfoByID).
HIDDEN = (
    ("TOY_HIDDEN", "The toys whose Flags in the Toy table have the 2 bit: Clicky's grid lists them only when owned."),
    ("MOUNT_HIDDEN", "The mounts whose Flags in the Mount table have the 0x40 bit: Clicky's grid lists them only"
     " when collected."),
    ("PET_HIDDEN", "The pet species whose Flags have HideFromJournal (0x20) or HideUntilLearned (0x4000):"
     " Clicky's grid lists them only when owned."),
    ("PET_RANDOM_LOOK", "The pet species whose Flags have RandomDisplay (0x800): a look each summon, so 0 is their"
     " only look."),
    ("TOY_SOURCE", "Each toy's source (the Toy table's SourceTypeEnum), if it has one."),
    ("MOUNT_TYPE", "Each mount type's Type in the MountType table, read as Enum.MountTypeFlag"
     " (C_MountJournal.GetMountInfoExtraByID gives a mount's mountTypeID), if it isn't 0."),
    ("PET_SOURCE", "Each pet species' source (the BattlePetSpecies table's SourceTypeEnum), if it has one."),
)
HIDDEN_HEADER = """
-- %s
ns.%s = {
"""
HIDDEN_START = re.compile(r'^ns\.(\w+) = \{$')

ENTRY_LINE = re.compile(r'^\t(?:(\d+)|"([sim])(\d+)"|"p(\d+):(\d+)"),$')
HIDDEN_LINE = re.compile(r'^\t\[(\d+)\] = (true|-?\d+),$')
BUILD_LINE = re.compile(r'^ns\.TOY_LIST_BUILD = "([^"]*)"$', re.MULTILINE)


def read_entries(text):
    """The (kind, ID) entries in a ToyList.lua, in order."""
    entries = []
    for line in text.splitlines():
        m = ENTRY_LINE.match(line)
        if m and m.group(1):
            entries.append(("", int(m.group(1))))
        elif m and m.group(2):
            entries.append((m.group(2), int(m.group(3))))
        elif m:
            entries.append(("p", (int(m.group(4)), int(m.group(5)))))
    return entries


def read_hidden(text):
    """A ToyList.lua's tables after the list: name (TOY_HIDDEN, ...) -> {ID: True or a number}."""
    hidden, current = {name: {} for name, _ in HIDDEN}, None
    for line in text.splitlines():
        start, m = HIDDEN_START.match(line), HIDDEN_LINE.match(line)
        if start:
            current = start.group(1)
        elif m and current in hidden:
            hidden[current][int(m.group(1))] = True if m.group(2) == "true" else int(m.group(2))
    return hidden


def value(v):
    return "true" if v is True else "%d" % v


def read_build(text):
    m = BUILD_LINE.search(text)
    return m.group(1) if m else None


def text(entry):
    """An entry as the list writes it, without quotes: 5, s5, i5, m5, p5:6."""
    kind, i = entry
    return "p%d:%d" % i if kind == "p" else "%s%d" % (kind, i)


def render(entries, build, hidden):
    """hidden: name (TOY_HIDDEN, ...) -> {ID: True or a number}, or a set of IDs for True."""
    def rows(t):
        t = dict.fromkeys(t, True) if isinstance(t, set) else t
        return "".join("\t[%d] = %s,\n" % (i, value(t[i])) for i in sorted(t))
    return HEADER % {"build": build} + "".join(
        ('\t"%s",\n' if kind else "\t%s,\n") % text((kind, i)) for kind, i in entries) + "}\n" \
        + "".join(HIDDEN_HEADER % (what, name) + rows(hidden.get(name, {})) + "}\n" for name, what in HIDDEN)


def merge(listed, in_game):
    """The new list: listed as it is, then the entries in the game that aren't listed: toys, spells,
    items, mounts, then pets, each sorted by ID.

    Returns (entries, added, missing): the entries appended, and the listed entries not in the game."""
    now = set(in_game)
    added = sorted(now - set(listed), key=lambda e: (KINDS.index(e[0]), e[1]))
    missing = [e for e in listed if e not in now]
    return listed + added, added, missing


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read().decode("utf-8")


def live_build():
    return json.loads(get(BUILDS_URL))["wow"]["version"]


# A spell's text shown only to a character who knows another spell, empty for everyone else.
GATED_TEXT = re.compile(r"^\$\?s\d+\[.*\]\[\]$", re.DOTALL)


def table(name, build):
    """A table's rows (Toy.csv has SourceText_lang with quoted commas, hence the csv module)."""
    return csv.DictReader(io.StringIO(get(CSV_URL % (name, build)), newline=""))


# The spells a character can learn: each table and its spell ID columns.
SPELL_COLUMNS = (
    ("SkillLineAbility", ("Spell",)),
    ("SpecializationSpells", ("SpellID", "OverridesSpellID")),
    ("TraitDefinition", ("SpellID", "OverridesSpellID", "VisibleSpellID")),
    ("PvpTalent", ("SpellID",)),
)


def spell_ids(build):
    """The spells a character can learn; stops if a table has none, rather than leave them out."""
    ids = set()
    for name, columns in SPELL_COLUMNS:
        found = set()
        for row in table(name, build):
            found |= {int(row[c]) for c in columns if int(row[c])}
        if not found:
            sys.exit("the %s table for build %s has no spells" % (name, build))
        ids |= found
    return ids


def used_item_ids(build):
    """The items with an effect of TriggerType 0, a "Use:" effect, whose text everyone sees."""
    spells = list(table("Spell", build))
    # Empty, it would let the gated items through, and the list keeps whatever it appends.
    if not spells:
        sys.exit("the Spell table for build %s is empty" % build)
    gated = {row["ID"] for row in spells if GATED_TEXT.match(row["Description_lang"])}
    on_use = set()
    for row in table("ItemEffect", build):
        if int(row["TriggerType"]) == 0 and row["SpellID"] not in gated:
            on_use.add(row["ID"])
    ids = set()
    for row in table("ItemXItemEffect", build):
        if int(row["ItemID"]) and row["ItemEffectID"] in on_use:
            ids.add(int(row["ItemID"]))
    return ids


# The Mount table's Flags bit for a mount the Mount Journal shows only when collected: unnamed in
# Blizzard's source and wowdev.wiki; its 443 mounts are mostly retired ones (Gray Wolf, White
# Stallion), and the grid's Not Collected count is compared with the journal's in play.
MOUNT_HIDDEN_FLAG = 0x40
# Enum.BattlePetSpeciesFlags HideFromJournal and HideUntilLearned.
PET_HIDDEN_FLAGS = 0x20 | 0x4000


def mount_ids(build):
    """Every mount in the Mount table, those it hides when not collected, and each mount type's flags
    where it has any."""
    rows = [row for row in table("Mount", build) if int(row["ID"])]
    types = {int(row["ID"]): int(row["Type"]) for row in table("MountType", build)}
    if rows and not types:
        sys.exit("the MountType table for build %s is empty" % build)
    return ({int(row["ID"]) for row in rows},
            {int(row["ID"]) for row in rows if int(row["Flags"]) & MOUNT_HIDDEN_FLAG},
            {i: t for i, t in types.items() if t})


# A species whose pets take a random look each time they're summoned (Enum.BattlePetSpeciesFlags
# RandomDisplay; wowdev.wiki DB/BattlePetSpecies): its looks aren't listed, so its pets are all its 0.
RANDOM_DISPLAY = 0x800


def pet_looks(build):
    """(species ID, display ID) for each look of each species (its creature's display IDs), and the
    species hidden when not owned, those whose looks are random, and each one's source."""
    displays = {}  # creature ID -> its display IDs
    tables = {name: list(table(name, build)) for name in
              ("BattlePetSpecies", "Creature", "CreatureXDisplayInfo", "BattlePetDisplayOverride")}
    for name, rows in tables.items():
        if not rows:
            sys.exit("build %s has no pets: the %s table is empty" % (build, name))
    creatures, by_creature = tables["Creature"], tables["CreatureXDisplayInfo"]
    for row in creatures:
        displays.setdefault(row["ID"], set()).update(
            int(row["DisplayID_%d" % i]) for i in range(4) if int(row["DisplayID_%d" % i]))
    for row in by_creature:
        if int(row["CreatureDisplayInfoID"]):
            displays.setdefault(row["CreatureID"], set()).add(int(row["CreatureDisplayInfoID"]))
    looks, random, hidden = set(), set(), set()  # random: the species with RandomDisplay
    sources = {}
    for row in tables["BattlePetSpecies"]:
        looks.add((int(row["ID"]), 0))
        if int(row["SourceTypeEnum"]) >= 0:
            sources[int(row["ID"])] = int(row["SourceTypeEnum"])
        if int(row["Flags"]) & PET_HIDDEN_FLAGS:
            hidden.add(int(row["ID"]))
        if int(row["Flags"]) & RANDOM_DISPLAY:
            random.add(int(row["ID"]))
            continue
        for display in displays.get(row["CreatureID"], ()):
            looks.add((int(row["ID"]), display))
    for row in tables["BattlePetDisplayOverride"]:
        if int(row["CreatureDisplayInfoID"]) and int(row["BattlePetSpeciesID"]) not in random:
            looks.add((int(row["BattlePetSpeciesID"]), int(row["CreatureDisplayInfoID"])))
    return looks, hidden, random, sources


def shown(entries):
    """": 1, 2, s3" for a few entries; nothing for none or for many."""
    return ": " + ", ".join(map(text, entries)) if 0 < len(entries) <= 50 else ""


def count(entries, kind):
    return sum(1 for k, _ in entries if k == kind)


def main():
    build = live_build()
    toy_rows = [row for row in table("Toy", build) if int(row["ItemID"])]
    toys = {int(row["ItemID"]) for row in toy_rows}
    hidden = {int(row["ItemID"]) for row in toy_rows if int(row["Flags"]) & 2}
    if not toys:
        sys.exit("the Toy table for build %s has no toys" % build)
    listed = []
    if os.path.exists(LIST_PATH):
        with open(LIST_PATH, encoding="utf-8") as f:
            listed = read_entries(f.read())
    spells = spell_ids(build)
    # A toy the game dropped is still listed as a toy, so it isn't listed again as an item.
    items = used_item_ids(build) - toys - {i for kind, i in listed if kind == ""}
    if not items:
        sys.exit("build %s has no items" % build)
    mounts, hidden_mounts, mount_types = mount_ids(build)
    if not mounts:
        sys.exit("the Mount table for build %s has no mounts" % build)
    pets, hidden_species, random_species, pet_sources = pet_looks(build)
    if not pets:
        sys.exit("build %s has no pets" % build)
    in_game = {("", i) for i in toys} | {("s", i) for i in spells} | {("i", i) for i in items} \
        | {("m", i) for i in mounts} | {("p", i) for i in pets}
    entries, added, missing = merge(listed, in_game)
    with open(LIST_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(entries, build, {
            "TOY_HIDDEN": hidden, "MOUNT_HIDDEN": hidden_mounts, "PET_HIDDEN": hidden_species,
            "PET_RANDOM_LOOK": random_species,
            "TOY_SOURCE": {int(row["ItemID"]): int(row["SourceTypeEnum"]) for row in toy_rows
                           if int(row["SourceTypeEnum"]) >= 0},
            "MOUNT_TYPE": mount_types, "PET_SOURCE": pet_sources}))
    print("build %s: %d toys (%d listed only when owned), %d spells, %d items, %d mounts (%d listed only"
          " when collected), %d pet looks (%d species listed only when owned) in the game; %d listed" % (
              build, len(toys), len(hidden), len(spells), len(items), len(mounts), len(hidden_mounts), len(pets),
              len(hidden_species), len(entries)))
    print("added %d toys, %d spells, %d items, %d mounts, %d pet looks%s" % (
        count(added, ""), count(added, "s"), count(added, "i"), count(added, "m"), count(added, "p"),
        shown(added)))
    print("listed but not in this build, kept: %d toys, %d spells, %d items, %d mounts, %d pet looks%s" % (
        count(missing, ""), count(missing, "s"), count(missing, "i"), count(missing, "m"), count(missing, "p"),
        shown(missing)))


if __name__ == "__main__":
    main()
