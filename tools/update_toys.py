#!/usr/bin/env python3
"""Writes ToyList.lua: the item IDs of every toy in the game, in the order Clicky numbers them.

A toy's Clicky number is its place in the list, so the list only ever grows at the end: the
first run writes every toy sorted by item ID, and later runs append the toys not listed yet
(sorted by item ID among themselves). A toy that left the game keeps its place.

The toys come from the game's Toy table for the live build (wago.tools). Python standard
library only. Running it again for the same build changes nothing.
"""

import csv
import io
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST_PATH = os.path.join(ROOT, "ToyList.lua")
USER_AGENT = "clicky-toylist/1.0 (+https://github.com/shadowpaxa/clicky)"
BUILDS_URL = "https://wago.tools/api/builds/latest"
# Without ?build= wago serves a build that isn't the live one.
TOY_CSV_URL = "https://wago.tools/db2/Toy/csv?build=%s"

HEADER = """\
-- Every toy in the game, as item IDs. A toy's number in Clicky's macros is its 0-based place in
-- this list, so the list only ever grows at the end: nothing is reordered or removed, and a toy
-- that left the game keeps its place.
-- Generated by tools/update_toys.py from the game's Toy table; don't edit by hand.
-- Last updated from WoW build %(build)s.

local _, ns = ...

ns.TOY_LIST_BUILD = "%(build)s"
ns.TOY_IDS = {
"""

ID_LINE = re.compile(r"^\t(\d+),$")
BUILD_LINE = re.compile(r'^ns\.TOY_LIST_BUILD = "([^"]*)"$', re.MULTILINE)


def read_ids(text):
    """The item IDs in a ToyList.lua, in order."""
    return [int(m.group(1)) for line in text.splitlines() if (m := ID_LINE.match(line))]


def read_build(text):
    m = BUILD_LINE.search(text)
    return m.group(1) if m else None


def render(ids, build):
    return HEADER % {"build": build} + "".join("\t%d,\n" % i for i in ids) + "}\n"


def merge(listed, in_game):
    """The new list: listed as it is, then the toys in the game that aren't listed, sorted.

    Returns (ids, added, missing): the toys appended, and the listed toys not in the game."""
    now = set(in_game)
    added = sorted(now - set(listed))
    missing = [i for i in listed if i not in now]
    return listed + added, added, missing


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read().decode("utf-8")


def live_build():
    return json.loads(get(BUILDS_URL))["wow"]["version"]


def toy_item_ids(build):
    """The distinct ItemIDs in the Toy table (columns SourceText_lang, ID, ItemID, Flags,
    SourceTypeEnum; SourceText has quoted commas, hence the csv module)."""
    ids = set()
    for row in csv.DictReader(io.StringIO(get(TOY_CSV_URL % build), newline="")):
        ids.add(int(row["ItemID"]))
    return ids


def shown(ids):
    """": 1, 2, 3" for a few IDs; nothing for none or for the whole first list."""
    return ": " + ", ".join(map(str, ids)) if 0 < len(ids) <= 50 else ""


def main():
    build = live_build()
    in_game = toy_item_ids(build)
    if not in_game:
        sys.exit("the Toy table for build %s has no toys" % build)
    listed = []
    if os.path.exists(LIST_PATH):
        with open(LIST_PATH, encoding="utf-8") as f:
            listed = read_ids(f.read())
    ids, added, missing = merge(listed, in_game)
    with open(LIST_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(ids, build))
    print("build %s: %d toys in the game, %d listed" % (build, len(in_game), len(ids)))
    print("added %d%s" % (len(added), shown(added)))
    print("listed but not in this build, kept: %d%s" % (len(missing), shown(missing)))


if __name__ == "__main__":
    main()
